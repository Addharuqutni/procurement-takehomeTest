def now() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")


def hash_password(password: str, salt: str | None = None) -> str:
    salt = salt or secrets.token_hex(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt.encode(), 200_000).hex()
    return f"{salt}${digest}"


def verify_password(password: str, stored: str) -> bool:
    salt, _, digest = stored.partition("$")
    return secrets.compare_digest(hash_password(password, salt), stored)


class Row(dict):
    """Dict row that also supports positional access, mirroring sqlite3.Row."""

    def __getitem__(self, key):
        if isinstance(key, str):
            return super().__getitem__(key)
        return list(self.values())[key]


def _pg_row_factory(cur):
    # Called for DDL too, where description is None.
    if not cur.description:
        return lambda values: values
    names = [d.name for d in cur.description]

    def make(values):
        return Row(zip(names, values, strict=True))

    return make


class _PGConn:
    """Adapts psycopg to the sqlite3 surface the app already uses."""

    def __init__(self, con):
        self.con = con
        self.cur = con.cursor()
        self.cur.row_factory = _pg_row_factory

    def execute(self, sql, params=()):
        # ponytail: "?" -> "%s" only works because no SQL literal here contains "?"
        return self.cur.execute(sql.replace("?", "%s"), params)

    def executemany(self, sql, rows):
        return self.cur.executemany(sql.replace("?", "%s"), rows)

    def commit(self):
        self.con.commit()

    def rollback(self):
        self.con.rollback()

    def close(self):
        self.con.close()


@contextmanager
def connect():
    if DATABASE_URL:
        raw = psycopg.connect(DATABASE_URL)
        con = _PGConn(raw)
    else:
        con = sqlite3.connect(DB_PATH)
        con.row_factory = sqlite3.Row
        con.execute("PRAGMA foreign_keys = ON")
        con.execute("PRAGMA journal_mode = WAL")
    try:
        yield con
        con.commit()
    except Exception:
        con.rollback()
        raise
    finally:
        con.close()


def init_schema() -> None:
    with connect() as con:
        if DATABASE_URL:
            con.execute(PG_SCHEMA)
        else:
            con.executescript(SCHEMA)


def init_db() -> None:
    init_schema()
    with connect() as con:
        if con.execute("SELECT COUNT(*) FROM users").fetchone()[0]:
            return
        for name, email, password, role, dept in DEMO_USERS:
            con.execute(
                "INSERT INTO users (name, email, password_hash, role, department) VALUES (?,?,?,?,?)",
                (name, email, hash_password(password), role, dept),
            )
        con.executemany("INSERT INTO vendors (name, contact, email) VALUES (?,?,?)", DEMO_VENDORS)
